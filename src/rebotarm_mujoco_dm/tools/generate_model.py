#!/usr/bin/env python3
"""Generate the B601-DM MJCF from the bringup URDF (no ROS or MuJoCo required).

This is intentionally a converter for this description, not a general URDF importer.
Missing finger inertia is approximated by a 40 g box enclosing its collision mesh.
"""
import argparse
import math
import os
from pathlib import Path
import struct
import xml.etree.ElementTree as ET
import numpy as np
from scipy.sparse import coo_matrix
from scipy.sparse.csgraph import connected_components
from scipy.spatial import ConvexHull

ROOT = Path(__file__).resolve().parents[1]
POSES = {
    "home": [0, 0, 0, 0, 0, 0, 0, 0],
    "ready": [0, -0.75, -0.55, 0, 0, 0, 0.025, -0.025],
    "pose_a": [0.3, -1.0, -0.8, 0.25, -0.3, 0.4, 0.04, -0.04],
    "pose_b": [-0.3, -0.6, -1.1, -0.2, 0.35, -0.5, 0.015, -0.015],
}


def numbers(values):
    return " ".join(format(float(v), ".16g") for v in values)


def pose(origin):
    if origin is None:
        return {"pos": "0 0 0", "quat": "1 0 0 0"}
    r, p, y = [float(v) / 2 for v in origin.get("rpy", "0 0 0").split()]
    cr, cp, cy = math.cos(r), math.cos(p), math.cos(y)
    sr, sp, sy = math.sin(r), math.sin(p), math.sin(y)
    # URDF Rz(yaw) Ry(pitch) Rx(roll), MuJoCo quaternion order w x y z.
    return {"pos": origin.get("xyz", "0 0 0"), "quat": numbers([
        cr*cp*cy + sr*sp*sy, sr*cp*cy - cr*sp*sy,
        cr*sp*cy + sr*cp*sy, cr*cp*sy - sr*sp*cy])}


def stl_bounds(path):
    data = path.read_bytes()
    n = struct.unpack_from("<I", data, 80)[0]
    if len(data) != 84 + 50*n:
        raise ValueError(f"Expected binary STL: {path}")
    vertices = [struct.unpack_from("<3f", data, 84 + 50*i + 12 + 12*j)
                for i in range(n) for j in range(3)]
    return ([min(v[k] for v in vertices) for k in range(3)],
            [max(v[k] for v in vertices) for k in range(3)])


def write_xml(root, path):
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(path, encoding="utf-8", xml_declaration=True)
    with path.open("a") as f:
        f.write("\n")


def plate_sections(triangles, width=0.01):
    """Conservative hulls of 10 mm X slabs for the concave elbow side plates.

    Clip triangles at each slab boundary so no source surface is discarded.
    This is an approximation, not a general exact convex decomposition.
    """
    low, high = triangles[:, :, 0].min(), triangles[:, :, 0].max()
    boundaries = np.linspace(low, high, math.ceil((high-low)/width)+1)
    for start, end in zip(boundaries[:-1], boundaries[1:]):
        selected = triangles[(triangles[:, :, 0].max(axis=1) >= start) &
                             (triangles[:, :, 0].min(axis=1) <= end)]
        points = []
        for triangle in selected:
            polygon = list(triangle)
            for boundary, sign in ((start, 1), (end, -1)):
                clipped = []
                for a, b in zip(polygon, polygon[1:] + polygon[:1]):
                    inside_a, inside_b = sign*(a[0]-boundary) >= 0, sign*(b[0]-boundary) >= 0
                    if inside_a:
                        clipped.append(a)
                    if inside_a != inside_b:
                        clipped.append(a + (b-a)*((boundary-a[0])/(b[0]-a[0])))
                polygon = clipped
            points.extend(polygon)
        yield np.unique(np.array(points), axis=0)


def generate(description, output):
    description = description.resolve()
    output.mkdir(parents=True, exist_ok=True)
    urdf = ET.parse(description / "urdf/ReBot_Arm_DM.urdf").getroot()
    links = {e.get("name"): e for e in urdf.findall("link")}
    joints = urdf.findall("joint")
    materials = {e.get("name"): e.find("color").get("rgba")
                 for e in urdf.findall("material")}
    robot = ET.Element("mujoco", model="ReBot_Arm_DM")
    robot.append(ET.Comment(" Generated by tools/generate_model.py; edit generator and regenerate. "))
    ET.SubElement(robot, "compiler", angle="radian", fusestatic="false",
                  inertiafromgeom="false")
    # implicitfast treats actuator damping implicitly and is stable at 1 ms.
    ET.SubElement(robot, "option", timestep="0.001", gravity="0 0 -9.81",
                  integrator="implicitfast", solver="Newton", iterations="100",
                  cone="elliptic", impratio="10", noslip_iterations="1")
    default = ET.SubElement(robot, "default")
    ET.SubElement(default, "joint", damping="0.1", armature="0.001",
                  solreflimit="0.01 1", solimplimit="0.95 0.99 0.001")
    ET.SubElement(default, "geom", friction="0.8 0.005 0.0001", condim="3")
    visual = ET.SubElement(default, "default", **{"class": "visual"})
    ET.SubElement(visual, "geom", type="mesh", contype="0", conaffinity="0", group="2", mass="0")
    collision = ET.SubElement(default, "default", **{"class": "collision"})
    ET.SubElement(collision, "geom", type="mesh", group="3", rgba="0.7 0.3 0.2 0.3", mass="0")
    asset = ET.SubElement(robot, "asset")
    mesh_names = {}
    collision_names = {}

    def collision_assets(mesh):
        # A single hull around an entire CAD assembly bridges its empty spaces.
        # Preserve disconnected solids as separate convex contact shapes.
        relative = mesh.get("filename").split("/meshes/", 1)[1]
        if relative in collision_names:
            return collision_names[relative]
        data = (description / "meshes" / relative).read_bytes()
        count = struct.unpack_from("<I", data, 80)[0]
        if len(data) != 84 + count * 50:
            raise ValueError(f"Expected binary STL: {relative}")
        dtype = np.dtype([("normal", "<f4", 3), ("v", "<f4", (3, 3)), ("attr", "<u2")])
        vertices = np.ndarray(count, dtype=dtype, buffer=data, offset=84)["v"]
        vertices, indices = np.unique(vertices.reshape(-1, 3), axis=0, return_inverse=True)
        triangles = indices.reshape(-1, 3)
        edges = np.concatenate([triangles[:, [0, 1]], triangles[:, [1, 2]], triangles[:, [0, 2]]])
        graph = coo_matrix((np.ones(len(edges)), (edges[:, 0], edges[:, 1])), shape=(len(vertices), len(vertices)))
        count, labels = connected_components(graph, directed=False)
        names = []
        for component in range(count):
            points = vertices[labels == component].astype(float)
            # These long, thin side plates contain concave edges. Whole-solid
            # hulls produce artificial link2/link4 contacts at the zero pose.
            split_plate = (relative == "collision/link2.STL" and component in (1, 2)) or (
                relative == "collision/link4.STL" and component in (0, 1))
            sections = plate_sections(vertices[triangles[labels[triangles[:, 0]] == component]].astype(float)) if split_plate else [points]
            for section, points in enumerate(sections):
                hull = ConvexHull(points)
                name = f"contact_{len(collision_names)}_{component}_{section}"
                # MuJoCo computes faces; retain only hull vertices.
                ET.SubElement(asset, "mesh", name=name, vertex=numbers(points[hull.vertices].ravel()),
                              scale=mesh.get("scale", "1 1 1"))
                names.append(name)
        collision_names[relative] = names
        return names

    def mesh_asset(mesh):
        prefix = "package://rebotarm_bringup/description/DM/meshes/"
        filename = mesh.get("filename")
        if not filename.startswith(prefix):
            raise ValueError(f"Unexpected mesh URI: {filename}")
        relative = filename[len(prefix):]
        if not (description / "meshes" / relative).is_file():
            raise FileNotFoundError(relative)
        if relative not in mesh_names:
            name = "mesh_" + str(len(mesh_names))
            mesh_names[relative] = name
            ET.SubElement(asset, "mesh", name=name,
                          file=os.path.relpath(description / "meshes" / relative, output.resolve()),
                          scale=mesh.get("scale", "1 1 1"))
        return mesh_names[relative]

    world = ET.SubElement(robot, "worldbody")

    def add_link(parent, name, joint=None):
        link = links[name]
        body = ET.SubElement(parent, "body", name=name, **pose(joint.find("origin") if joint is not None else None))
        inertial = link.find("inertial")
        if inertial is not None:
            origin = inertial.find("origin")
            if origin is not None and any(float(v) for v in origin.get("rpy", "0 0 0").split()):
                raise ValueError("Nonzero inertia frame rotation needs explicit tensor rotation")
            tensor = inertial.find("inertia")
            ET.SubElement(body, "inertial", pos=pose(origin)["pos"],
                          mass=inertial.find("mass").get("value"),
                          fullinertia=" ".join(tensor.get(k) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")))
        else:
            if name not in ("finger_left_link", "finger_right_link"):
                raise ValueError(f"Missing inertial data: {name}")
            mesh = link.find("collision/geometry/mesh")
            relative = mesh.get("filename").split("/meshes/", 1)[1]
            low, high = stl_bounds(description / "meshes" / relative)
            lengths = [b-a for a, b in zip(low, high)]
            mass = 0.04
            body.append(ET.Comment(" URDF has no inertia: assumed 0.04 kg, collision AABB box inertia. "))
            ET.SubElement(body, "inertial", mass=str(mass),
                          pos=numbers([(a+b)/2 for a,b in zip(low,high)]),
                          diaginertia=numbers([mass/12 * sum(lengths[k]**2 for k in range(3) if k != axis) for axis in range(3)]))
        if joint is not None and joint.get("type") != "fixed":
            limit = joint.find("limit")
            ET.SubElement(body, "joint", name=joint.get("name"),
                          type={"revolute": "hinge", "prismatic": "slide"}[joint.get("type")],
                          axis=joint.find("axis").get("xyz"), limited="true",
                          range=f"{limit.get('lower')} {limit.get('upper')}",
                          actuatorfrclimited="true", actuatorfrcrange=f"-{limit.get('effort')} {limit.get('effort')}")
        for kind in ("visual", "collision"):
            for i, element in enumerate(link.findall(kind)):
                mesh = element.find("geometry/mesh")
                if mesh is None:
                    raise ValueError("Only the current DM mesh geometry is supported")
                attrs = {"name": f"{name}_{kind}_{i}", "class": kind, **pose(element.find("origin"))}
                material = element.find("material")
                if kind == "visual" and material is not None:
                    attrs["rgba"] = materials[material.get("name")]
                if kind == "visual":
                    ET.SubElement(body, "geom", attrs, mesh=mesh_asset(mesh))
                else:
                    for part, mesh_name in enumerate(collision_assets(mesh)):
                        ET.SubElement(body, "geom", {**attrs, "name": f"{name}_{kind}_{i}_{part}", "mesh": mesh_name})
        if name == "end_link":
            # Matches gripper_tcp_joint in rebotarm_moveit_config/rebotarm.urdf.xacro.
            ET.SubElement(body, "site", name="gripper_tcp", pos="0 0 0", size="0.004", rgba="1 0.2 0.1 1", group="1")
        for child in joints:
            if child.find("parent").get("link") == name:
                add_link(body, child.find("child").get("link"), child)

    add_link(world, "base_link")
    contact = ET.SubElement(robot, "contact")
    for joint in joints:
        ET.SubElement(contact, "exclude", body1=joint.find("parent").get("link"), body2=joint.find("child").get("link"))
    # The crossed racks overlap in the mesh; mirrors the DM SRDF finger-pair exclusion.
    ET.SubElement(contact, "exclude", body1="finger_left_link", body2="finger_right_link")
    equality = ET.SubElement(robot, "equality")
    ET.SubElement(equality, "joint", name="finger_mimic", joint1="finger_right", joint2="finger_left",
                  polycoef="0 -1 0 0 0", solref="0.005 1", solimp="0.99 0.999 0.0001")
    actuator = ET.SubElement(robot, "actuator")
    gains = [(1200, 50), (1200, 50), (1000, 30), (400, 10), (250, 6), (200, 5), (800, 8)]
    commanded = [j for j in joints if j.get("type") != "fixed" and j.find("mimic") is None]
    for joint, (kp, kv) in zip(commanded, gains):
        limit = joint.find("limit")
        ET.SubElement(actuator, "position", name=joint.get("name"), joint=joint.get("name"),
                      kp=str(kp), kv=str(kv), ctrllimited="true", forcelimited="true",
                      ctrlrange=f"{limit.get('lower')} {limit.get('upper')}",
                      forcerange="-6 6" if joint.get("name") == "finger_left" else
                      f"-{limit.get('effort')} {limit.get('effort')}")
    keyframes = ET.SubElement(robot, "keyframe")
    for name, q in POSES.items():
        ET.SubElement(keyframes, "key", name=name, qpos=numbers(q), ctrl=numbers(q[:7]))
    write_xml(robot, output / "dm_arm.xml")

    scene = ET.Element("mujoco", model="B601_DM_scene")
    ET.SubElement(scene, "include", file="dm_arm.xml")
    ET.SubElement(scene, "statistic", center="0.12 0 0.2", extent="0.75")
    visual = ET.SubElement(scene, "visual")
    ET.SubElement(visual, "headlight", diffuse="0.7 0.7 0.7", ambient="0.3 0.3 0.3", specular="0.1 0.1 0.1")
    ET.SubElement(visual, "global", azimuth="135", elevation="-25")
    asset = ET.SubElement(scene, "asset")
    ET.SubElement(asset, "texture", name="floor_texture", type="2d", builtin="checker", rgb1="0.22 0.26 0.3", rgb2="0.12 0.15 0.18", width="256", height="256")
    ET.SubElement(asset, "material", name="floor_material", texture="floor_texture", texrepeat="8 8", texuniform="true")
    world = ET.SubElement(scene, "worldbody")
    ET.SubElement(world, "light", pos="0 -0.5 1.5", dir="0 0 -1", directional="true")
    ET.SubElement(world, "geom", name="floor", type="plane", size="1 1 0.05", pos="0 0 -0.002", material="floor_material", group="0")
    write_xml(scene, output / "dm_empty.xml")
    # The scene is edited independently as manipulation phases are added.
    if not (output / "dm_scene.xml").exists():
        write_xml(scene, output / "dm_scene.xml")
    print(f"Generated dm_arm.xml and dm_empty.xml using {description}; existing dm_scene.xml preserved")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--description", type=Path, default=ROOT.parent / "rebotarm_bringup/description/DM")
    parser.add_argument("--output", type=Path, default=ROOT / "models")
    args = parser.parse_args()
    generate(args.description, args.output)
